// כל מה שנחקר, ומקבל גם את המטרה מההצעה כדי שיוכל לאתגר אותה.
// גרסה 1: מעתיקים את הפרומפט לצ'אט שכבר משתמשים בו. גרסה 2 (בהמשך): בוט מוטמע.
//
// שני עקרונות שלא משנים: ה-AI שואל ולא כותב בשבילן, ואין בפרומפט שמות של תלמידות.
import { inOrg, REAL_ORG, TYPE_REAL_ORG } from './shared.js';

function line(label, value) {
  return value ? `- ${label}: ${value}` : '';
}

export function buildRolePlay(v) {
  const isF = v('client_gender') === 'אישה';
  const name = v('client_name') || (isF ? 'בעלת התפקיד' : 'בעל התפקיד');
  const role = v('client_role') || 'בעל תפקיד';
  const type = v('client_type');
  const realOrg = REAL_ORG.includes(type);

  const facts = [
    line('מה עושים ביום רגיל בתפקיד', v('role_day')),
    line('מה נחשב הצלחה בתפקיד', v('success')),
    line('מה הארגון עושה ולמי', v('org_history')),
    line('סוג הארגון', v('sector')),
    line('מטרת העל', v('org_goal')),
    line('היקף הפעילות', v('org_scale')),
    line('מה קורה בארגון עכשיו', v('current_activity')),
    realOrg ? line('עובדות שאספנו (עם מקורות)', v('org_sources')) : line('הארגון בנוי לפי עסקים אמיתיים', v('fict_basis')),
    line('מתחרים וארגונים דומים', v('competitors')),
    line('מה קורה בשוק', v('market_trend')),
    line('מה לדעתנו לוחץ על הלקוח', v('pressure')),
  ].filter(Boolean).join('\n');

  const data = [
    v('db_name') ? `מסד הנתונים "${v('db_name')}"` : 'מסד נתונים',
    v('db_country') ? `מ${v('db_country')}` : '',
    v('db_years') ? `(${v('db_years')})` : '',
    v('db_rows') ? `— ${v('db_rows')} שורות` : '',
    v('db_cols') ? `ו-${v('db_cols')} עמודות` : '',
  ].filter(Boolean).join(' ');

  let truthRule;
  if (!realOrg) {
    truthRule = 'הדמות והארגון מומצאים. אל תמציא פרטים שסותרים את מה שכתוב כאן. אם חסר פרט, שאל אותנו מה החלטנו.';
  } else {
    truthRule = (type === TYPE_REAL_ORG ? 'הדמות מומצאת, אבל הארגון והתפקיד אמיתיים. ' : 'הארגון אמיתי. ')
      + 'אם אינך בטוח בעובדה עליו, אמור "את זה כדאי לבדוק במקור". אל תמציא מספרים.';
  }

  return `בוא נעשה משחק תפקידים, בעברית.

הדמות שלך: ${name}, ${role} ${inOrg(v('org'))}. ${isF ? 'הדמות היא אישה, ולכן דבר בלשון נקבה.' : ''}
מה ידוע על הדמות, על הארגון ועל הסביבה:
${facts || '- (עוד לא מילאנו פרטים)'}

אנחנו צוות אנליסטים צעיר (תלמידי תיכון) שמכין לך דוח אנליטי. יש לנו ${data}${v('db_support') ? `, ומסד תומך: ${v('db_support')}` : ''}.
עמודות חשובות: ${v('db_columns') || '(עוד לא כתבנו)'}.
המטרה שכתבנו בהצעת המחקר: ${v('proposal_goal') || '(עוד לא כתבנו)'}

איך משחקים:
1. דבר כמו בעל התפקיד באמת: 2 עד 4 משפטים בכל תור, בלי רשימות ובלי כותרות.
2. פתח בהצגה קצרה של עצמך, וספר מה מטריד אותך עכשיו בעבודה.
3. עזור לנו להבין את הכאב שלך. ראיין אותנו ותן לנו לראיין אותך, שאלה אחת בכל פעם: מה בדיוק מטריד אותך, למה דווקא עכשיו, מה יקרה אם לא תעשה כלום, ומי עוד בארגון מושפע.
4. אתגר את המטרה שכתבנו: האם היא באמת תעזור לך להחליט משהו? מה תעשה ביום שאחרי הדוח? אם התשובה שלנו כללית, לחץ: "מה זה אומר בפועל?"
5. אל תכתוב בשבילנו את הדוח, את המטרה או את הפרק. התפקיד שלך הוא לשאול ולספר מה אתה צריך.
6. ${truthRule}
7. אחרי כ-8 תורות, או כשנכתוב "סיכום", צא מהדמות וכתוב שלוש שורות: מה הכי כואב ללקוח, איזו החלטה הוא צריך לקבל, ומה עדיין לא ברור בהגדרה שלנו.
8. שמור על שפה מכבדת ומתאימה לבני נוער.

התחל עכשיו, בתוך הדמות.`;
}

