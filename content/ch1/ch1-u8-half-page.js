// יחידה 8: חצי העמוד. הטיוטה נבנית מהתשובות (buildDraft), ומשם היא שלהן:
// עורכות, מונה המילים מכוון לחצי עמוד, ומעתיקות לוורד. מבנה הפסקאות לפי
// המחוון: לקוח ורקע ← הכאב ← המטרה האנליטית.
import { inOrg } from './shared.js';

function sentence(s) {
  const t = String(s || '').trim().replace(/\s*\n+\s*/g, ' ');
  if (!t) return '';
  return /[.!?]$/.test(t) ? t : t + '.';
}

export function buildDraft(v) {
  const isF = v('client_gender') === 'אישה';
  const name = v('client_name') || '[שם]';
  const role = v('client_role') || '[תפקיד]';

  // תוויות ולא משפטים מחוברים: התשובות נכתבו כקטעים, והטיוטה צריכה
  // להיראות כמו טיוטה, כזו שברור שצריך לכתוב מחדש.
  const p1 = [
    `${isF ? 'הלקוחה של הדוח היא' : 'הלקוח של הדוח הוא'} ${name}, ${role} ${inOrg(v('org') || '[ארגון]')}.`,
    v('org_history') ? sentence(`הארגון: ${v('org_history')}`) : '',
    v('org_scale') ? sentence(`היקף הפעילות: ${v('org_scale')}`) : '',
    v('current_activity') ? sentence(`בימים אלה: ${v('current_activity')}`) : '',
    v('market_trend') ? sentence(`בתחום: ${v('market_trend')}`) : '',
    v('competitors') ? sentence(`מתחרים: ${v('competitors')}`) : '',
  ].filter(Boolean).join(' ');

  const p2 = [sentence(v('pain')), sentence(v('why_now'))].filter(Boolean).join(' ')
    || '[מה כואב ללקוח, ולמה הוא צריך את הדוח עכשיו]';

  const source = [v('db_country'), v('db_years')].filter(Boolean).join(', ');
  const p3 = [
    `מטרת הדוח היא לספק ל${name} תמונת מצב על ${v('goal_topic') || '[הנושא]'}, כדי ${isF ? 'שתוכל' : 'שיוכל'} להחליט ${v('goal_decision') || '[ההחלטה]'}.`.replace(/\.\./g, '.'),
    `הניתוח יתבסס על ${v('db_name') || '[המסד]'}${source ? ` (${source})` : ''}${v('goal_columns') ? `, ובעיקר על העמודות: ${v('goal_columns')}` : ''}.`,
  ].join(' ');

  return [p1, p2, p3].join('\n\n');
}

